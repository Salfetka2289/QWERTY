    def calculate_expression(self, expression):
        """Вычисляет математическое выражение"""
        try:
            # Заменяем русские символы на английские
            expression = expression.replace('х', '*').replace('Х', '*')
            expression = expression.replace(',', '.')
            expression = expression.replace('÷', '/').replace(':', '/')
            
            # Убираем лишние пробелы
            expression = re.sub(r'\s+', '', expression)
            
            # Проверяем безопасность выражения
            if re.search(r'[^0-9+\-*/().]', expression):
                return "Ошибка: Выражение содержит недопустимые символы"
            
            # Вычисляем
            result = eval(expression)
            return f"{expression} = {result}"
            
        except ZeroDivisionError:
            return "Ошибка: Деление на ноль"
        except:
            return "Ошибка: Не могу вычислить выражение"

    def get_response(self, user_input):
        """Получить ответ на вопрос пользователя"""
        user_input = user_input.lower().strip()
        
        # Проверяем, является ли запрос математическим выражением
        math_pattern = r'^[\d+\-*/()., хХ÷:]+$'
        if re.match(math_pattern, user_input) and any(char in user_input for char in '+-*/'):
            return self.calculate_expression(user_input)
        
        # Проверяем специальные математические запросы
        math_queries = {
            r'\bпосчитай\b|\bвычисли\b|\bреши\b': lambda: self.calculate_expression(user_input.replace('посчитай', '').replace('вычисли', '').replace('реши', '')),
            r'\bсколько будет (.+)': lambda: self.calculate_expression(re.search(r'сколько будет (.+)', user_input).group(1)),
            r'\bвычисли (.+)': lambda: self.calculate_expression(re.search(r'вычисли (.+)', user_input).group(1)),
        }
        
        for pattern, func in math_queries.items():
            if re.search(pattern, user_input):
                return func()
        
        # Проверяем все шаблоны в базе знаний
        for pattern, response in self.knowledge_base.items():
            if re.search(pattern, user_input):
                return response
        
        # Если не нашли подходящего ответа, возвращаем случайный из default_responses
        return random.choice(self.default_responses)

